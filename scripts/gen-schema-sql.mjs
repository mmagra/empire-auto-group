// Regenerates src/lib/schema-sql.ts from prisma/schema.prisma.
//
//   npm run db:sql
//
// The app runs this SQL on first start to create the tables (see src/lib/db.ts).
// If you change the schema after the site is live, the existing database will
// not be altered automatically; add the needed ALTER TABLE statements by hand.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const sql = execFileSync("npx", ["prisma", "migrate", "diff", "--from-empty", "--to-schema-datamodel", "prisma/schema.prisma", "--script"], {
  encoding: "utf8",
});

writeFileSync(
  "src/lib/schema-sql.ts",
  `// Generated by scripts/gen-schema-sql.mjs from prisma/schema.prisma. Do not edit.\nexport const SCHEMA_SQL = ${JSON.stringify(sql)};\n`,
);
console.log("Wrote src/lib/schema-sql.ts");
